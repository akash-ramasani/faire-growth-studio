"use client";

import Link from "next/link";
import { useRouter } from "next/navigation";
import { useMemo, useState } from "react";
import { EvalList, EvalSummary } from "@/components/EvalList";
import { LandingPage } from "@/components/LandingPage";
import { CATEGORIES, CHANNELS, TONES, type Category } from "@/lib/landing/catalog";
import { createExperiment, learningPrompt, relevantLearnings } from "@/lib/experiments/model";
import { blockingFailures, runEvals } from "@/lib/landing/evals";
import { LOCALE_CONFIG, LOCALES, type Locale } from "@/lib/landing/locale";
import type { Brief, GenerationResult, PageSpec } from "@/lib/landing/schema";
import { addRun, publishPage, saveExperiment, useLearnings, usePages } from "@/lib/store";

const PRESETS: Array<{ label: string; brief: Brief }> = [
  {
    label: "Holiday restock · retailers",
    brief: {
      campaignName: "Holiday Restock 2026",
      audience: "retailer",
      channel: "paid_social",
      goal: "Get gift shops and boutiques to place their first holiday order before the November rush.",
      keyMessage: "Unique, small-batch gifts your customers can't find at big-box stores.",
      offer: "Free shipping on qualifying opening orders",
      tone: "warm",
      focusCategories: ["Candles & Fragrance", "Gifts & Novelty"],
      locale: "en-US",
    },
  },
  {
    label: "Win-back · lapsed retailers",
    brief: {
      campaignName: "Spring Win-back",
      audience: "retailer",
      channel: "lifecycle_email",
      goal: "Bring back retailers who haven't ordered in 120+ days with new arrivals in their top categories.",
      keyMessage: "Thousands of new brands joined since your last order.",
      offer: "",
      tone: "confident",
      focusCategories: ["Home Decor"],
      locale: "en-US",
    },
  },
  {
    label: "Brand acquisition · makers",
    brief: {
      campaignName: "Makers Go Wholesale",
      audience: "brand",
      channel: "paid_search",
      goal: "Convince independent jewelry and beauty makers to apply to sell wholesale on Faire.",
      keyMessage: "Retailers come to you, and you stop chasing invoices.",
      offer: "",
      tone: "editorial",
      focusCategories: ["Jewelry", "Beauty & Wellness"],
      locale: "en-US",
    },
  },
];

const SOURCE_COPY: Record<GenerationResult["source"], { label: string; cls: string }> = {
  claude: { label: "Generated by Claude", cls: "bg-pass-bg text-pass" },
  claude_repaired: { label: "Claude, repaired after evals", cls: "bg-warn-bg text-warn" },
  template_fallback: { label: "Approved template fallback", cls: "bg-sky text-ink" },
};

const CHANNEL_LABEL: Record<(typeof CHANNELS)[number], string> = {
  paid_social: "Paid social",
  paid_search: "Paid search",
  lifecycle_email: "Lifecycle email",
  blog: "Blog",
  newsroom: "Newsroom",
};

type Draft = { key: string; label: string; result: GenerationResult; learningsApplied: number };

export default function PagesStudio() {
  const router = useRouter();
  const [brief, setBrief] = useState<Brief>(PRESETS[0].brief);
  const [drafts, setDrafts] = useState<Draft[]>([]);
  const [activeKey, setActiveKey] = useState("A");
  const [edited, setEdited] = useState<PageSpec | null>(null);
  const [tab, setTab] = useState<"preview" | "evals" | "json">("preview");
  const [loading, setLoading] = useState<null | "A" | "B" | "localize">(null);
  const [error, setError] = useState<string | null>(null);
  const published = usePages();
  const allLearnings = useLearnings();
  const [useLearned, setUseLearned] = useState(true);
  const [justPublished, setJustPublished] = useState<string | null>(null);

  const learnings = useLearned ? relevantLearnings(allLearnings, brief) : [];
  const currentDraft = drafts.find((d) => d.key === activeKey) ?? drafts[0];
  const current = currentDraft?.result;
  const spec = edited ?? current?.spec;
  const evals = useMemo(() => (spec ? runEvals(spec) : []), [spec]);
  const blocked = blockingFailures(evals).length > 0;
  const draftA = drafts.find((d) => d.key === "A");
  const draftB = drafts.find((d) => d.key === "B");

  const set = <K extends keyof Brief>(k: K, v: Brief[K]) => setBrief((b) => ({ ...b, [k]: v }));

  async function requestPage(b: Brief, variantHint?: string): Promise<Draft["result"]> {
    const res = await fetch("/api/pages/generate", {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: JSON.stringify({ brief: b, variantHint, learnings: learnings.map(learningPrompt) }),
    });
    const data = await res.json();
    if (!res.ok) throw new Error(data.error ?? "Generation failed");
    const result = data as GenerationResult;
    addRun({
      at: Date.now(),
      kind: "page",
      campaign: `${b.campaignName}${b.locale === "en-US" ? "" : ` (${b.locale})`}`,
      source: result.source,
      latencyMs: result.latencyMs,
      attempts: result.attempts,
      evals: result.evals.map(({ id, name, passed, severity }) => ({ id, name, passed, severity })),
      fallbackReason: result.fallbackReason,
      inputTokens: result.usage?.inputTokens,
      outputTokens: result.usage?.outputTokens,
    });
    return result;
  }

  async function generate(mode: "A" | "B" | "localize") {
    setLoading(mode);
    setError(null);
    setJustPublished(null);
    try {
      if (mode === "localize") {
        const others = LOCALES.filter((l) => l !== brief.locale);
        const results = await Promise.all(others.map((locale) => requestPage({ ...brief, locale })));
        const localized = others.map((locale, i) => ({ key: locale, label: LOCALE_CONFIG[locale].flag, result: results[i], learningsApplied: learnings.length }));
        setDrafts((d) => [...d.filter((x) => x.key === "A" || x.key === "B"), ...localized]);
        setActiveKey(others[0]);
      } else {
        const hint =
          mode === "B"
            ? `Write a clearly different B variant from this A headline: "${draftA?.result.spec.hero.headline}". Lead with a different benefit and use a different palette.`
            : undefined;
        const result = await requestPage(brief, hint);
        const draft = { key: mode, label: `Variant ${mode}`, result, learningsApplied: learnings.length };
        setDrafts((d) => (mode === "A" ? [draft] : [...d.filter((x) => x.key !== "B"), draft]));
        setActiveKey(mode);
      }
      setEdited(null);
      setTab("preview");
    } catch (e) {
      setError(e instanceof Error ? e.message : String(e));
    } finally {
      setLoading(null);
    }
  }

  function startTest() {
    if (!draftA || !draftB) return;
    const exp = createExperiment(draftA.result, draftB.result);
    saveExperiment(exp);
    router.push(`/experiments?id=${exp.id}`);
  }

  function editHero(field: "headline" | "subhead" | "ctaLabel", value: string) {
    if (!spec) return;
    setEdited({ ...spec, hero: { ...spec.hero, [field]: value } });
  }

  function publish() {
    if (!spec || blocked || !current) return;
    publishPage({ spec, publishedAt: Date.now(), source: current.source });
    setJustPublished(spec.slug);
  }

  return (
    <div className="mx-auto max-w-[1440px] px-4 py-10 sm:px-8">
      <div className="mb-8 flex flex-col justify-between gap-3 md:flex-row md:items-end">
        <div>
          <p className="text-sm text-ink-soft">Landing page service</p>
          <h1 className="mt-1 font-serif text-[30px] leading-[38px] md:text-[38px] md:leading-[50px]">From brief to live page, without a ticket</h1>
          <p className="mt-2 max-w-2xl text-sm text-ink-soft">
            Claude writes the copy against a typed schema and approved catalogs. Code adds tracking. Evals gate publishing. If anything fails, the approved
            template takes over.
          </p>
        </div>
      </div>

      <div className="grid gap-6 lg:grid-cols-[360px_1fr]">
        <aside className="space-y-5">
          <div className="card p-5">
            <div className="mb-4 flex flex-wrap gap-2">
              {PRESETS.map((p) => (
                <button
                  key={p.label}
                  onClick={() => setBrief(p.brief)}
                  className={`pill pill-sm ${
                    brief.campaignName === p.brief.campaignName ? "pill-active" : ""
                  }`}
                >
                  {p.label}
                </button>
              ))}
            </div>
            <div className="space-y-4">
              <div>
                <label className="label" htmlFor="campaign">Campaign name</label>
                <input id="campaign" className="field" value={brief.campaignName} onChange={(e) => set("campaignName", e.target.value)} />
              </div>
              <div className="grid grid-cols-2 gap-3">
                <div>
                  <label className="label" htmlFor="aud">Audience</label>
                  <select id="aud" className="field" value={brief.audience} onChange={(e) => set("audience", e.target.value as Brief["audience"])}>
                    <option value="retailer">Retailers</option>
                    <option value="brand">Brands</option>
                  </select>
                </div>
                <div>
                  <label className="label" htmlFor="channel">Channel</label>
                  <select id="channel" className="field" value={brief.channel} onChange={(e) => set("channel", e.target.value as Brief["channel"])}>
                    {CHANNELS.map((c) => (
                      <option key={c} value={c}>
                        {CHANNEL_LABEL[c]}
                      </option>
                    ))}
                  </select>
                </div>
              </div>
              <div>
                <span className="label">Market</span>
                <div className="grid grid-cols-4 gap-1.5">
                  {LOCALES.map((l: Locale) => (
                    <button
                      key={l}
                      onClick={() => set("locale", l)}
                      title={LOCALE_CONFIG[l].label}
                      className={`pill pill-sm justify-center ${brief.locale === l ? "pill-active" : ""}`}
                    >
                      {LOCALE_CONFIG[l].flag}
                    </button>
                  ))}
                </div>
              </div>
              <div>
                <label className="label" htmlFor="goal">Goal</label>
                <textarea id="goal" rows={3} className="field resize-none" value={brief.goal} onChange={(e) => set("goal", e.target.value)} />
              </div>
              <div>
                <label className="label" htmlFor="msg">Key message</label>
                <input id="msg" className="field" value={brief.keyMessage} onChange={(e) => set("keyMessage", e.target.value)} />
              </div>
              <div>
                <label className="label" htmlFor="offer">Offer (optional)</label>
                <input id="offer" className="field" placeholder="e.g. Free shipping on qualifying orders" value={brief.offer} onChange={(e) => set("offer", e.target.value)} />
              </div>
              <div>
                <span className="label">Tone</span>
                <div className="flex flex-wrap gap-2">
                  {TONES.map((t) => (
                    <button
                      key={t}
                      onClick={() => set("tone", t)}
                      className={`pill pill-sm capitalize ${brief.tone === t ? "pill-active" : ""}`}
                    >
                      {t}
                    </button>
                  ))}
                </div>
              </div>
              <div>
                <span className="label">Focus categories (up to 4)</span>
                <div className="flex flex-wrap gap-1.5">
                  {CATEGORIES.map((c) => {
                    const on = brief.focusCategories.includes(c);
                    return (
                      <button
                        key={c}
                        onClick={() =>
                          set(
                            "focusCategories",
                            on ? brief.focusCategories.filter((x) => x !== c) : ([...brief.focusCategories, c].slice(-4) as Category[]),
                          )
                        }
                        className={`pill pill-sm ${on ? "pill-active" : ""}`}
                      >
                        {c}
                      </button>
                    );
                  })}
                </div>
              </div>
            </div>
            {allLearnings.length > 0 && (
              <label className="mt-5 flex items-start gap-2 rounded-[4px] bg-sage/60 p-3 text-xs text-ink-soft">
                <input type="checkbox" className="mt-0.5" checked={useLearned} onChange={(e) => setUseLearned(e.target.checked)} />
                <span>
                  Apply {relevantLearnings(allLearnings, brief).length} learning{relevantLearnings(allLearnings, brief).length === 1 ? "" : "s"} from past {brief.audience} tests.{" "}
                  <Link href="/experiments" className="underline">
                    See them
                  </Link>
                </span>
              </label>
            )}
            <div className="mt-5 flex gap-2">
              <button className="btn flex-1" disabled={loading !== null || brief.goal.length < 10} onClick={() => generate("A")}>
                {loading === "A" ? "Generating…" : drafts.length ? "Regenerate" : "Generate page"}
              </button>
              <button className="btn-outline" disabled={loading !== null || !draftA} onClick={() => generate("B")} title="Generate a B variant for an A/B test">
                {loading === "B" ? "…" : "+ Variant B"}
              </button>
            </div>
            <div className="mt-2 grid grid-cols-2 gap-2">
              <button className="btn-outline btn-sm" disabled={loading !== null || !draftA} onClick={() => generate("localize")}>
                {loading === "localize" ? "Localizing…" : "Localize to all markets"}
              </button>
              <button className="btn-outline btn-sm" disabled={!draftA || !draftB} onClick={startTest} title="Needs variants A and B">
                Start A/B test →
              </button>
            </div>
            {error && <p className="mt-3 text-sm text-fail">{error}</p>}
          </div>

          {spec && (
            <div className="card p-5">
              <p className="label">Edit hero</p>
              <p className="mb-3 text-xs text-muted">Evals re-run on every keystroke.</p>
              <div className="space-y-3">
                <input aria-label="Headline" className="field" value={spec.hero.headline} onChange={(e) => editHero("headline", e.target.value)} />
                <textarea aria-label="Subhead" rows={3} className="field resize-none" value={spec.hero.subhead} onChange={(e) => editHero("subhead", e.target.value)} />
                <input aria-label="CTA label" className="field" value={spec.hero.ctaLabel} onChange={(e) => editHero("ctaLabel", e.target.value)} />
              </div>
            </div>
          )}

          {published.length > 0 && (
            <div className="card p-5">
              <p className="label">Published in this browser</p>
              <ul className="mt-2 space-y-2 text-sm">
                {published.slice(0, 6).map((p) => (
                  <li key={p.spec.slug} className="flex items-center justify-between gap-2">
                    <Link href={`/p/${p.spec.slug}`} className="truncate underline-offset-2 hover:underline">
                      /p/{p.spec.slug}
                    </Link>
                    <span className="shrink-0 text-xs text-muted">{new Date(p.publishedAt).toLocaleDateString()}</span>
                  </li>
                ))}
              </ul>
            </div>
          )}
        </aside>

        <section className="min-w-0">
          {!spec ? (
            <div className="card flex min-h-[560px] flex-col items-center justify-center bg-cream p-10 text-center">
              <p className="font-serif text-2xl">Your page preview appears here</p>
              <p className="mt-2 max-w-sm text-sm text-ink-soft">Pick a preset or write a brief, then generate. Without an API key, the approved template shows how the fallback works.</p>
            </div>
          ) : (
            <div className="card overflow-hidden">
              <div className="flex flex-wrap items-center gap-3 border-b border-line px-4 py-3">
                {drafts.length > 1 && (
                  <div className="flex flex-wrap gap-2">
                    {drafts.map((d) => (
                      <button
                        key={d.key}
                        onClick={() => {
                          setActiveKey(d.key);
                          setEdited(null);
                        }}
                        className={`pill pill-sm ${currentDraft?.key === d.key ? "pill-active" : ""}`}
                      >
                        {d.label}
                      </button>
                    ))}
                  </div>
                )}
                <div className="flex gap-1 text-sm">
                  {(["preview", "evals", "json"] as const).map((t) => (
                    <button key={t} onClick={() => setTab(t)} className={`rounded-[4px] px-3 py-1.5 capitalize ${tab === t ? "bg-cream font-medium" : "text-ink-soft"}`}>
                      {t === "json" ? "Spec" : t}
                    </button>
                  ))}
                </div>
                <div className="ml-auto flex flex-wrap items-center gap-2">
                  <EvalSummary evals={evals} />
                  <button className="btn btn-sm" disabled={blocked} onClick={publish} title={blocked ? "Fix blocking evals to publish" : "Publish page"}>
                    Publish
                  </button>
                </div>
              </div>

              <div className="flex flex-wrap items-center gap-x-4 gap-y-1 border-b border-line bg-cream/60 px-4 py-2 text-xs text-ink-soft">
                <span className={`rounded-full px-2 py-0.5 font-medium ${SOURCE_COPY[current.source].cls}`}>{SOURCE_COPY[current.source].label}</span>
                {edited && <span className="rounded-full bg-white px-2 py-0.5 font-medium">Edited by marketer</span>}
                <span>{LOCALE_CONFIG[current.spec.brief.locale].label}</span>
                {currentDraft.learningsApplied > 0 && current.source !== "template_fallback" && (
                  <span className="rounded-full bg-sage px-2 py-0.5 font-medium text-ink">{currentDraft.learningsApplied} learnings applied</span>
                )}
                <span>{(current.latencyMs / 1000).toFixed(1)}s</span>
                <span>
                  {current.attempts} model call{current.attempts === 1 ? "" : "s"}
                </span>
                {current.usage && <span>{(current.usage.inputTokens + current.usage.outputTokens).toLocaleString()} tokens</span>}
                {current.fallbackReason && <span className="text-ink">Why fallback: {current.fallbackReason}</span>}
              </div>

              {justPublished && (
                <div className="flex items-center justify-between border-b border-line bg-pass-bg px-4 py-2.5 text-sm text-pass">
                  <span>Published to /p/{justPublished}</span>
                  <Link href={`/p/${justPublished}`} className="font-medium underline">
                    Open page
                  </Link>
                </div>
              )}

              {tab === "preview" && (
                <div className="max-h-[78vh] overflow-y-auto">
                  <LandingPage spec={spec} />
                </div>
              )}
              {tab === "evals" && (
                <div className="p-5">
                  <p className="mb-2 text-sm text-ink-soft">
                    Blocking checks gate publishing and trigger one repair round with Claude before falling back. Warnings are advisory.
                  </p>
                  <EvalList evals={evals} />
                </div>
              )}
              {tab === "json" && (
                <pre className="max-h-[78vh] overflow-auto bg-[#1d1d1b] p-5 text-xs leading-relaxed text-[#e9e4da]">
                  {JSON.stringify({ ...spec, brief: undefined }, null, 2)}
                </pre>
              )}
            </div>
          )}
        </section>
      </div>
    </div>
  );
}
