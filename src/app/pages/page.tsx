const SOURCE_COPY: Record<GenerationResult["source"], { label: string; cls: string }> = {
  claude: { label: "Generated by Claude", cls: "bg-pass-bg text-pass" },
  claude_repaired: { label: "Claude, repaired after evals", cls: "bg-warn-bg text-warn" },
  template_fallback: { label: "Approved template fallback", cls: "bg-sky text-ink" },
};

const CHANNEL_LABEL: Record<(typeof CHANNELS)[number], string> = {
  paid_social: "Paid social",
  paid_search: "Paid search",
  lifecycle_email: "Lifecycle email",
  blog: "Blog",
  newsroom: "Newsroom",
};

const STEPS = ["Writing copy against the page schema", "Running up to 15 brand and compliance checks", "Repairing anything that failed", "Building tracking links"];

// Shown while Claude works: an honest progress indicator (steps advance on a timer; the real
// pipeline reports its path when it finishes) over a skeleton of the page layout.
function GeneratingPanel({ label }: { label: string }) {
  const [step, setStep] = useState(0);
  useEffect(() => {
    const id = setInterval(() => setStep((s) => Math.min(s + 1, STEPS.length - 1)), 4500);
    return () => clearInterval(id);
  }, []);
  return (
    <div className="card animate-fade-in overflow-hidden" aria-busy="true">
      <div className="progress-track">
        <span />
      </div>
      <div className="flex items-center gap-3 border-b border-line px-4 py-3 text-sm">
        <span className="spinner text-ink" aria-hidden />
        <span className="font-medium">{label}</span>
        <span key={step} className="animate-fade-up text-ink-soft">
          {STEPS[step]}…
        </span>
      </div>
      <div className="grid gap-8 bg-cream p-8 md:grid-cols-2">
        <div className="space-y-4">
          <div className="skeleton h-4 w-28" />
          <div className="skeleton h-10 w-11/12" />
          <div className="skeleton h-10 w-3/4" />
          <div className="skeleton h-4 w-full" />
          <div className="skeleton h-4 w-5/6" />
          <div className="skeleton h-12 w-40" />
        </div>
        <div className="skeleton aspect-[6/5] w-full" />
      </div>
      <div className="grid grid-cols-3 gap-6 p-8">
        {[0, 1, 2].map((i) => (
          <div key={i} className="space-y-3">
            <div className="skeleton h-10 w-10 rounded-full" />
            <div className="skeleton h-5 w-2/3" />
            <div className="skeleton h-4 w-full" />
          </div>
        ))}
      </div>
    </div>
  );
}

const SOURCE_TOAST: Record<GenerationResult["source"], string> = {
  claude: "written by Claude and passed every blocking check",
  claude_repaired: "written by Claude, fixed in one repair round",
  template_fallback: "served from the approved template",
};

type Draft = { key: string; label: string; result: GenerationResult; learningsApplied: number };

export default function PagesStudio() {
  const router = useRouter();
  const [brief, setBrief] = useState<Brief>(PRESETS[0].brief);
  const [drafts, setDrafts] = useState<Draft[]>([]);
  const [activeKey, setActiveKey] = useState("A");
  const [edited, setEdited] = useState<PageSpec | null>(null);
  const [tab, setTab] = useState<"preview" | "evals" | "json">("preview");
  const [loading, setLoading] = useState<null | "A" | "B" | "localize">(null);
  const [error, setError] = useState<string | null>(null);
  const { data: published } = usePages();
  const { data: allLearnings } = useLearnings();
  const [publishing, setPublishing] = useState(false);
  const [useLearned, setUseLearned] = useState(true);
  const [justPublished, setJustPublished] = useState<string | null>(null);

  const currentDraft = drafts.find((d) => d.key === activeKey) ?? drafts[0];
  const current = currentDraft?.result;
  const spec = edited ?? current?.spec;
  const evals = useMemo(() => (spec ? runEvals(spec) : []), [spec]);
  const blocked = blockingFailures(evals).length > 0;
  const draftA = drafts.find((d) => d.key === "A");
  const draftB = drafts.find((d) => d.key === "B");

  const set = <K extends keyof Brief>(k: K, v: Brief[K]) => setBrief((b) => ({ ...b, [k]: v }));

  async function requestPage(b: Brief, variantHint?: string) {
    const res = await fetch("/api/pages/generate", {
      method: "POST",
      headers: { "content-type": "application/json" },
      // The server looks up matching learnings itself and logs the run to SQLite.
      body: JSON.stringify({ brief: b, variantHint, applyLearnings: useLearned }),
    });
    const data = await res.json();
    if (!res.ok) throw new Error(data.error ?? "Generation failed");
    return data as GenerationResult & { learningsApplied: number };
  }


  async function generate(mode: "A" | "B" | "localize") {
    setLoading(mode);
    setError(null);
    setJustPublished(null);
    try {
      if (mode === "localize") {
        const others = LOCALES.filter((l) => l !== brief.locale);
        const results = await Promise.all(others.map((locale) => requestPage({ ...brief, locale })));
        const localized = others.map((locale, i) => ({ key: locale, label: LOCALE_CONFIG[locale].flag, result: results[i], learningsApplied: results[i].learningsApplied }));
        setDrafts((d) => [...d.filter((x) => x.key === "A" || x.key === "B"), ...localized]);
        setActiveKey(others[0]);
        toast(`Localized for ${others.length} markets`, { tone: "success" });
      } else {
        const hint =
          mode === "B"
            ? `Write a clearly different B variant from this A headline: "${draftA?.result.spec.hero.headline}". Lead with a different benefit and use a different palette.`
            : undefined;
        const result = await requestPage(brief, hint);
        const draft = { key: mode, label: `Variant ${mode}`, result, learningsApplied: result.learningsApplied };
        setDrafts((d) => (mode === "A" ? [draft] : [...d.filter((x) => x.key !== "B"), draft]));
        setActiveKey(mode);
        toast(`Variant ${mode} ${SOURCE_TOAST[result.source]}`, { tone: result.source === "template_fallback" ? "default" : "success" });
      }
      setEdited(null);
      setTab("preview");
    } catch (e) {
      const message = e instanceof Error ? e.message : String(e);
      setError(message);
      toast(message, { tone: "error" });
    } finally {
      setLoading(null);
    }
  }

  async function startTest() {
    if (!draftA || !draftB) return;
    setError(null);
    const created = await createExperiment(
      { spec: draftA.result.spec, source: draftA.result.source },
      { spec: draftB.result.spec, source: draftB.result.source },
    );
    if (created.ok && created.id) {
      toast("A/B test started", { tone: "success" });
      router.push(`/experiments?id=${created.id}`);
    } else toast(created.error ?? "Could not start the test", { tone: "error" });
  }

  function editHero(field: "headline" | "subhead" | "ctaLabel", value: string) {
    if (!spec) return;
    setEdited({ ...spec, hero: { ...spec.hero, [field]: value } });
  }

  async function publish() {
    if (!spec || blocked || !current) return;
    setPublishing(true);
    setError(null);
    // The server re-runs the evals and rebuilds the URL before anything is stored.
    const res = await publishPage(spec, current.source);
    setPublishing(false);
    if (res.ok && res.slug) {
      setJustPublished(res.slug);
      toast(`Published /p/${res.slug}`, { tone: "success", action: { label: "Open", href: `/p/${res.slug}` } });
    } else toast(res.error ?? "Publishing failed", { tone: "error" });
  }

  return (
    <div className="mx-auto max-w-[1440px] px-4 py-10 sm:px-8">
      <div className="mb-8 flex flex-col justify-between gap-3 md:flex-row md:items-end">
        <div>
          <p className="text-sm text-ink-soft">Landing page service</p>
          <h1 className="mt-1 font-serif text-[30px] leading-[38px] md:text-[38px] md:leading-[50px]">From brief to live page, without a ticket</h1>
          <p className="mt-2 max-w-2xl text-sm text-ink-soft">
            Claude writes the copy against a typed schema and approved catalogs. Code adds tracking. Evals gate publishing. If anything fails, the approved
            template takes over.
          </p>
        </div>
      </div>

      <div className="grid gap-6 lg:grid-cols-[360px_1fr]">
        <aside className="space-y-5">
          <div className="card p-5">
            <div className="mb-4 flex flex-wrap gap-2">
              {PRESETS.map((p) => (
                <button
                  key={p.label}
                  onClick={() => setBrief(p.brief)}
                  className={`pill pill-sm ${
                    brief.campaignName === p.brief.campaignName ? "pill-active" : ""
                  }`}
                >
                  {p.label}
                </button>
              ))}
            </div>
            <div className="space-y-4">
              <div>
                <label className="label" htmlFor="campaign">Campaign name</label>
                <input id="campaign" className="field" value={brief.campaignName} onChange={(e) => set("campaignName", e.target.value)} />
              </div>
              <div className="grid grid-cols-2 gap-3">
                <div>
                  <label className="label" htmlFor="aud">Audience</label>
                  <select id="aud" className="field" value={brief.audience} onChange={(e) => set("audience", e.target.value as Brief["audience"])}>
                    <option value="retailer">Retailers</option>
                    <option value="brand">Brands</option>
                  </select>
                </div>
                <div>
                  <label className="label" htmlFor="channel">Channel</label>
                  <select id="channel" className="field" value={brief.channel} onChange={(e) => set("channel", e.target.value as Brief["channel"])}>
                    {CHANNELS.map((c) => (
                      <option key={c} value={c}>
                        {CHANNEL_LABEL[c]}
                      </option>
                    ))}
                  </select>
                </div>
              </div>
              <div>
                <span className="label" id="market-label">Market</span>
                <div className="segmented segmented-fill" role="radiogroup" aria-labelledby="market-label">
                  {LOCALES.map((l: Locale) => (
                    <button
                      key={l}
                      role="radio"
                      aria-checked={brief.locale === l}
                      onClick={() => set("locale", l)}
                      title={LOCALE_CONFIG[l].label}
                      className={`segment ${brief.locale === l ? "segment-active" : ""}`}
                    >
                      <Flag code={LOCALE_FLAG[l]} />
                      <span className="ml-1.5">{LOCALE_CONFIG[l].flag}</span>
                    </button>
                  ))}
                </div>
              </div>
              <div>
                <label className="label" htmlFor="goal">Goal</label>
                <textarea id="goal" rows={3} className="field resize-none" value={brief.goal} onChange={(e) => set("goal", e.target.value)} />
              </div>
              <div>
                <label className="label" htmlFor="msg">Key message</label>
                <input id="msg" className="field" value={brief.keyMessage} onChange={(e) => set("keyMessage", e.target.value)} />
              </div>
              <div>
                <label className="label" htmlFor="offer">Offer (optional)</label>
                <input id="offer" className="field" placeholder="e.g. Free shipping on qualifying orders" value={brief.offer} onChange={(e) => set("offer", e.target.value)} />
              </div>
              <div>
                <span className="label" id="tone-label">Tone</span>
                <div className="segmented segmented-fill" role="radiogroup" aria-labelledby="tone-label">
                  {TONES.map((t) => (
                    <button
                      key={t}
                      role="radio"
                      aria-checked={brief.tone === t}
                      onClick={() => set("tone", t)}
                      className={`segment capitalize ${brief.tone === t ? "segment-active" : ""}`}
                    >
                      {t}
                    </button>
                  ))}
                </div>
              </div>
              <div>
                <span className="label">Focus categories</span>
                <div className="flex flex-wrap gap-1.5">
                  {CATEGORIES.map((c) => {
                    const on = brief.focusCategories.includes(c);
                    return (
                      <button
                        key={c}
                        onClick={() =>
                          set(
                            "focusCategories",
                            on ? brief.focusCategories.filter((x) => x !== c) : ([...brief.focusCategories, c].slice(-4) as Category[]),
                          )
                        }
                        aria-pressed={on}
                        className={`pill pill-sm ${on ? "pill-active" : ""}`}
                      >
                        {c}
                      </button>
                    );
                  })}
                </div>
                <p className="help-text">Up to 4. The page features these first.</p>
              </div>
            </div>
            {allLearnings.length > 0 && (
              <label className="mt-5 flex cursor-pointer items-start gap-3 bg-cream p-3 text-sm leading-5">
                <input type="checkbox" className="check mt-px" checked={useLearned} onChange={(e) => setUseLearned(e.target.checked)} />
                <span>
                  Apply {relevantLearnings(allLearnings, brief).length} learning{relevantLearnings(allLearnings, brief).length === 1 ? "" : "s"} from past {brief.audience} tests.{" "}
                  <Link href="/experiments" className="link">
                    See them
                  </Link>
                </span>
              </label>
            )}
            <div className="mt-5 flex gap-2">
              <button className="btn flex-1" disabled={loading !== null || brief.goal.length < 10} onClick={() => generate("A")}>
                {loading === "A" ? "Generating…" : drafts.length ? "Regenerate" : "Generate page"}
              </button>
              <button className="btn-outline" disabled={loading !== null || !draftA} onClick={() => generate("B")} title="Generate a B variant for an A/B test">
                {loading === "B" ? "…" : "+ Variant B"}
              </button>
            </div>
            <div className="mt-2 grid grid-cols-2 gap-2">
              <button className="btn-outline btn-sm" disabled={loading !== null || !draftA} onClick={() => generate("localize")}>
                {loading === "localize" ? "Localizing…" : "Localize to all markets"}
              </button>
              <button className="btn-outline btn-sm" disabled={!draftA || !draftB} onClick={startTest} title="Needs variants A and B">
                Start A/B test →
              </button>
            </div>
            {error && <p className="mt-3 text-sm text-fail">{error}</p>}
          </div>

          {spec && (
            <div className="card p-5">
              <p className="section-title mb-1">Edit hero</p>
              <p className="help-text mt-0 mb-3">Evals re-run on every keystroke.</p>
              <div className="space-y-3">
                <div>
                  <label className="label" htmlFor="hero-headline">Headline</label>
                  <input id="hero-headline" className="field" value={spec.hero.headline} onChange={(e) => editHero("headline", e.target.value)} />
                  <p className="help-text">{spec.hero.headline.length}/70 characters</p>
                </div>
                <div>
                  <label className="label" htmlFor="hero-subhead">Subhead</label>
                  <textarea id="hero-subhead" rows={3} className="field resize-none" value={spec.hero.subhead} onChange={(e) => editHero("subhead", e.target.value)} />
                  <p className="help-text">{spec.hero.subhead.length}/160 characters</p>
                </div>
                <div>
                  <label className="label" htmlFor="hero-cta">Button label</label>
                  <input id="hero-cta" className="field" value={spec.hero.ctaLabel} onChange={(e) => editHero("ctaLabel", e.target.value)} />
                </div>
              </div>
            </div>
          )}

          {published.length > 0 && (
            <div className="card p-5">
              <p className="section-title">Recently published</p>
              <ul className="mt-2 space-y-2 text-sm">
                {published.slice(0, 6).map((p) => (
                  <li key={p.spec.slug} className="flex items-center justify-between gap-2">
                    <Link href={`/p/${p.spec.slug}`} className="link truncate">
                      /p/{p.spec.slug}
                    </Link>
                    <span className="shrink-0 text-xs text-muted">{new Date(p.publishedAt).toLocaleDateString()}</span>
                  </li>
                ))}
              </ul>
            </div>
          )}
        </aside>

        <section className="min-w-0">
          {loading && (loading !== "localize" || !spec) ? (
            <GeneratingPanel label={loading === "localize" ? "Localizing for 3 markets" : `Generating variant ${loading}`} />
          ) : !spec ? (
            <div className="card animate-fade-in flex min-h-[560px] flex-col items-center justify-center bg-cream p-10 text-center">
              <p className="font-serif text-2xl">Your page preview appears here</p>
              <p className="mt-2 max-w-sm text-sm text-ink-soft">Pick a preset or write a brief, then generate. Claude writes the page; if it fails the checks twice, the approved template takes over.</p>
            </div>
          ) : (
            <div className="card overflow-hidden">
              <div className="flex flex-wrap items-center gap-3 border-b border-line px-4 py-3">
                {drafts.length > 1 && (
                  <div className="segmented" role="tablist" aria-label="Drafts">
                    {drafts.map((d) => (
                      <button
                        key={d.key}
                        role="tab"
                        aria-selected={currentDraft?.key === d.key}
                        onClick={() => {
                          setActiveKey(d.key);
                          setEdited(null);
                        }}
                        className={`segment gap-1.5 ${currentDraft?.key === d.key ? "segment-active" : ""}`}
                      >
                        {LOCALE_FLAG[d.key] && <Flag code={LOCALE_FLAG[d.key]} />}
                        {d.label}
                      </button>
                    ))}
                  </div>
                )}
                <div className="segmented" role="tablist" aria-label="View">
                  {(["preview", "evals", "json"] as const).map((t) => (
                    <button key={t} role="tab" aria-selected={tab === t} onClick={() => setTab(t)} className={`segment capitalize ${tab === t ? "segment-active" : ""}`}>
                      {t === "json" ? "Spec" : t}
                    </button>
                  ))}
                </div>
                <div className="ml-auto flex flex-wrap items-center gap-2">
                  <EvalSummary evals={evals} />
                  <button className="btn btn-sm" disabled={blocked || publishing} onClick={publish} title={blocked ? "Fix blocking evals to publish" : "Publish page"}>
                    {publishing ? "Publishing…" : "Publish"}
                  </button>
                </div>
              </div>

              <div className="flex flex-wrap items-center gap-x-4 gap-y-1 border-b border-line bg-cream/60 px-4 py-2 text-xs text-ink-soft">
                <span className={`rounded-[2px] px-1.5 leading-5 ${SOURCE_COPY[current.source].cls}`}>{SOURCE_COPY[current.source].label}</span>
                {edited && <span className="tag bg-white">Edited by marketer</span>}
                <span className="inline-flex items-center gap-1.5">
                  <Flag code={LOCALE_FLAG[current.spec.brief.locale]} />
                  {LOCALE_CONFIG[current.spec.brief.locale].label}
                </span>
                {currentDraft.learningsApplied > 0 && current.source !== "template_fallback" && (
                  <span className="tag bg-sage">{currentDraft.learningsApplied} learnings applied</span>
                )}
                <span>{(current.latencyMs / 1000).toFixed(1)}s</span>
                <span>
                  {current.attempts} model call{current.attempts === 1 ? "" : "s"}
                </span>
                {current.usage && <span>{(current.usage.inputTokens + current.usage.outputTokens).toLocaleString()} tokens</span>}
                {current.fallbackReason && <span className="text-ink">Why fallback: {current.fallbackReason}</span>}
              </div>

              {error && <p className="border-b border-line bg-fail-bg px-4 py-2.5 text-sm text-fail">{error}</p>}
              {justPublished && (
                <div className="animate-fade-up flex items-center justify-between border-b border-line bg-pass-bg px-4 py-2.5 text-sm text-pass">
                  <span>Published to /p/{justPublished}. Anyone with the link can open it.</span>
                  <Link href={`/p/${justPublished}`} className="font-medium underline">
                    Open page
                  </Link>
                </div>
              )}

              {tab === "preview" && (
                <div key={currentDraft?.key + spec.hero.palette} className="animate-fade-in">
                  <LandingPage spec={spec} />
                </div>
              )}
              {tab === "evals" && (
                <div className="p-5">
                  <p className="mb-2 text-sm text-ink-soft">
                    Blocking checks gate publishing and trigger one repair round with Claude before falling back. Warnings are advisory.
                  </p>
                  <EvalList evals={evals} />
                </div>
              )}
              {tab === "json" && (
                <pre className="no-scrollbar max-h-[78vh] overflow-auto bg-[#1d1d1b] p-5 text-xs leading-relaxed text-[#e9e4da]">
                  {JSON.stringify({ ...spec, brief: undefined }, null, 2)}
                </pre>
              )}
            </div>
          )}
        </section>
      </div>
    </div>
  );
}
